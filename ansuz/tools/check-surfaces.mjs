// Run against an already served browser build: bun tools/check-surfaces.mjs [URL]
import {mkdirSync} from 'node:fs';
import {resolve} from 'node:path';
import {chromium} from '../../tooling/exact2/node_modules/playwright-core/index.mjs';
const out=resolve(import.meta.dir,'../artifacts/surfaces');
mkdirSync(out,{recursive:true});
const browser=await chromium.launch({headless:true,executablePath:chromium.executablePath(),args:['--enable-unsafe-webgpu','--no-sandbox','--use-mock-keychain','--password-store=basic']});
try {
 const page=await browser.newPage({viewport:{width:1280,height:720}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const ready=()=>page.waitForFunction(()=>{const el=document.querySelector('[data-gpu-input]');return el&&globalThis.exact?.gpu?.wantsInput(Number(el.dataset.view));},null,{timeout:60000});
 const textIs=async(id,text)=>{console.log(`Expect ${id}: ${text}`);return page.waitForFunction(({id,text})=>document.querySelector(`[data-testid="${id}"]`)?.textContent===text,{id,text});};
 const button=id=>page.locator(`[data-testid="${id}"]`);
 const settled=()=>page.waitForFunction(()=>document.querySelector('[data-testid="ascend"]')?.disabled===false);
 await page.goto(process.argv[2]??'http://127.0.0.1:8766');await ready();
 const atmosphere=await page.screenshot({path:resolve(out,'atmosphere.png')});
 await page.mouse.move(640,350);await page.mouse.down();await page.mouse.move(820,420,{steps:12});await page.mouse.up();await page.waitForTimeout(250);
 const rotated=await page.screenshot({path:resolve(out,'rotated.png')});
 if(atmosphere.equals(rotated))throw new Error('Atmospheric drag did not move the scene');
 if(await button('face-panel').count())throw new Error('Dragging selected a face');
 await button('reset').click();await page.waitForTimeout(100);
 await page.mouse.move(640,360);await page.waitForTimeout(100);await page.screenshot({path:resolve(out,'hover.png')});
 await page.mouse.click(640,360);await textIs('face-title','Empty surface');await settled();
 await page.screenshot({path:resolve(out,'focused.png')});
 if(await page.locator('[data-testid="tablet-content"], [data-testid="tablet-right"], [data-testid="descend"]').count())throw new Error('Old tablet controls remain');
 await button('add-note').click();
 await button('note-title').fill('A surface question');await button('note-body').fill('What grows here?');
 await button('save').click();await textIs('face-title','A surface question');await textIs('surface-title','A surface question');await textIs('surface-body','What grows here?');
 await page.screenshot({path:resolve(out,'saved.png')});
 await page.reload();await ready();await page.mouse.click(640,360);
 await textIs('face-title','A surface question');await textIs('face-body','What grows here?');await settled();
 await button('add-note').click();
 if(await button('note-body').inputValue()!=='What grows here?')throw new Error('Face opened a different note');
 await button('note-title').fill('The same root, edited');await textIs('surface-title','The same root, edited');
 await button('save').click();await textIs('face-title','The same root, edited');
 await button('deselect').click();await button('hint').waitFor();
 await page.mouse.move(50,100);await page.waitForTimeout(100);await page.screenshot({path:resolve(out,'occupied.png')});
 await page.mouse.move(640,360);await page.waitForTimeout(100);await page.screenshot({path:resolve(out,'occupied-hover.png')});
 await page.mouse.click(860,300);await textIs('face-title','Empty surface');await settled();
 await button('add-note').click();await button('note-body').fill('A neighbouring thought');
 await button('save').click();await textIs('face-title','Untitled note');
 await page.reload();await ready();await page.mouse.click(640,360);await textIs('face-title','The same root, edited');await settled();
 await button('ascend').click();await button('hint').waitFor();await page.waitForTimeout(1100);
 await page.screenshot({path:resolve(out,'returned.png')});
 await page.setViewportSize({width:390,height:844});await button('select-center').click();await settled();
 await page.screenshot({path:resolve(out,'portrait.png')});
 if(errors.length)throw new Error(errors.join('\n'));
 console.log('PASS mouse orbit, click-to-focus, landscape return, no tablet, create/edit/reload, separate neighbouring face, body-only note, portrait');
} finally {await browser.close();}
